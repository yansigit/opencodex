/**
 * Allowlisted report DTO: safe fields only, stable key order, no payload text,
 * no transport error contents, no credentials, aliases, or account identifiers.
 */
export function serializeBenchmarkReport(report: TokenBenchmarkReport): string {
  const dtos = [...report.fixtures]
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map(row => {
      const base = {
        id: row.id,
        schemaVersion: row.schemaVersion,
        digest: row.digest,
        state: row.state,
      };
      if (row.state === "supported" && row.metrics) {
        const m = row.metrics;
        return {
          ...base,
          metrics: {
            localTokens: m.localTokens,
            authoritativeTokens: m.authoritativeTokens,
            signedError: m.signedError,
            absoluteError: m.absoluteError,
            relativeError: roundTo(m.relativeError, METRIC_DECIMALS),
            absoluteTolerance: m.absoluteTolerance,
            passed: m.passed,
          },
        };
      }
      if (row.state === "unsupported") {
        return { ...base, unsupportedReason: row.unsupportedReason ?? "malformed_usage" };
      }
      return { ...base, failureReason: row.failureReason ?? "transport_failed" };
    });
  const s = report.summary;
  const dto = {
    reportSchemaVersion: report.reportSchemaVersion,
    fixtureSchemaVersion: report.fixtureSchemaVersion,
    modelId: report.modelId,
    providerKind: report.providerKind,
    status: report.status,
    summary: {
      fixtureCount: s.fixtureCount,
      supportedCount: s.supportedCount,
      unsupportedCount: s.unsupportedCount,
      failedCount: s.failedCount,
      allSupportedPassed: s.allSupportedPassed,
      weightedAbsoluteError: roundTo(s.weightedAbsoluteError, METRIC_DECIMALS),
      weightedErrorWithinLimit: s.weightedErrorWithinLimit,
    },
    fixtures: dtos,
  };
  return JSON.stringify(dto, null, 2);
}

/** Deterministic human rendering from the same closed DTO. */
export function formatBenchmarkReport(report: TokenBenchmarkReport): string {
  const lines: string[] = [];
  lines.push(`Token estimation accuracy benchmark — report schema ${report.reportSchemaVersion}`);
  lines.push(`provider kind: ${report.providerKind}  model: ${report.modelId}`);
  const s = report.summary;
  lines.push(
    `fixtures: ${s.fixtureCount}  supported: ${s.supportedCount}  unsupported: ${s.unsupportedCount}  failed: ${s.failedCount}`,
  );
  lines.push(
    `weighted absolute error: ${s.weightedAbsoluteError}  within 10% limit: ${s.weightedErrorWithinLimit}`,
  );
  lines.push(`status: ${report.status}`);
  for (const row of [...report.fixtures].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    const head = `- ${row.id} [${row.state}] digest=${row.digest}`;
    if (row.state === "supported" && row.metrics) {
      const m = row.metrics;
      lines.push(`${head} local=${m.localTokens} authoritative=${m.authoritativeTokens} absErr=${m.absoluteError} tol=${m.absoluteTolerance} passed=${m.passed}`);
    } else if (row.state === "unsupported") {
      lines.push(`${head} reason=${row.unsupportedReason ?? "malformed_usage"}`);
    } else {
      lines.push(`${head} reason=${row.failureReason ?? "transport_failed"}`);
    }
  }
  return lines.join("\n");
}
